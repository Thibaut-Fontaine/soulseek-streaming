// Generates every app icon asset from tools/icon/icon.mjs:
//   Android adaptive icon (foreground, background, monochrome) + legacy PNGs,
//   iOS AppIcon PNGs, showcase/img/icon.png, and prints the in-app logo
//   transform (src/ui/track.tsx, AppLogo).
// Needs Playwright with Chromium (preinstalled in Claude Code cloud sessions;
// elsewhere: `npm i -g playwright && npx playwright install chromium`).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { COLORS, GLYPH, GLYPH_SIZE, OPTICAL, glyphSvg, nodesPathData, trianglePathData } from './icon.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const RES = path.join(ROOT, 'android/app/src/main/res');
const IOS = path.join(ROOT, 'ios/SoulStream/Images.xcassets/AppIcon.appiconset');

const browser = await chromium.launch();
const page = await browser.newPage();

/** Bounding box and centre of mass of the glyph, measured on a render. */
async function measureGlyph() {
  const R = 800;
  await page.setViewportSize({ width: R, height: R });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${R}" height="${R}" viewBox="0 0 100 100"><rect width="100" height="100" fill="#fff"/>${glyphSvg('#000')}</svg>`;
  return page.evaluate(async ({ svg, R }) => {
    const img = new Image();
    img.src = 'data:image/svg+xml;base64,' + btoa(svg);
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = canvas.height = R;
    const ctx = canvas.getContext('2d');
    ctx.drawImage(img, 0, 0);
    const d = ctx.getImageData(0, 0, R, R).data;
    let sx = 0, sy = 0, n = 0, x0 = R, x1 = 0, y0 = R, y1 = 0;
    for (let y = 0; y < R; y++) {
      for (let x = 0; x < R; x++) {
        if (d[(y * R + x) * 4] < 128) {
          sx += x; sy += y; n++;
          x0 = Math.min(x0, x); x1 = Math.max(x1, x + 1); y0 = Math.min(y0, y); y1 = Math.max(y1, y + 1);
        }
      }
    }
    const f = 100 / R;
    return { cx: (sx / n + 0.5) * f, cy: (sy / n + 0.5) * f, x0: x0 * f, x1: x1 * f, y0: y0 * f, y1: y1 * f };
  }, { svg, R });
}

const m = await measureGlyph();
const scale = GLYPH_SIZE / Math.max(m.x1 - m.x0, m.y1 - m.y0);
const bx = (m.x0 + m.x1) / 2, by = (m.y0 + m.y1) / 2;
const px = bx + OPTICAL.x * (m.cx - bx), py = by + OPTICAL.y * (m.cy - by);
/** Glyph transform in a 100-unit visible icon: translate(tx, ty) scale(scale). */
const T = { s: scale, tx: 50 - px * scale, ty: 50 - py * scale };
const r4 = v => Number(v.toFixed(4));

function iconSvg(size, shape) {
  const clip = shape === 'circle' ? '<circle cx="50" cy="50" r="50"/>' : shape === 'rounded' ? '<rect width="100" height="100" rx="22"/>' : '<rect width="100" height="100"/>';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 100 100">
<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${COLORS.bgStart}"/><stop offset="1" stop-color="${COLORS.bgEnd}"/></linearGradient><clipPath id="clip">${clip}</clipPath></defs>
<g clip-path="url(#clip)"><rect width="100" height="100" fill="url(#bg)"/><g transform="translate(${r4(T.tx)} ${r4(T.ty)}) scale(${r4(T.s)})">${glyphSvg(COLORS.glyph)}</g></g></svg>`;
}

async function png(file, size, shape, opaque = false) {
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(`<body style="margin:0;background:transparent">${iconSvg(size, shape)}</body>`);
  const buffer = await page.screenshot({ omitBackground: !opaque, clip: { x: 0, y: 0, width: size, height: size } });
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, buffer);
  console.log('wrote', path.relative(ROOT, file));
}

// Android adaptive icon: 108 dp canvas, the launcher shows the centre 72 dp.
const A = { s: 0.72 * T.s, tx: 18 + 0.72 * T.tx, ty: 18 + 0.72 * T.ty };
const foreground = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/generate.mjs from tools/icon/icon.mjs. Do not edit. -->
<!-- Play button drawn by three connected peers, optically centred. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="${r4(A.s)}"
        android:scaleY="${r4(A.s)}"
        android:translateX="${r4(A.tx)}"
        android:translateY="${r4(A.ty)}">
        <path
            android:pathData="${trianglePathData()}"
            android:strokeColor="${COLORS.glyph}"
            android:strokeWidth="${GLYPH.triangle.strokeWidth}"
            android:strokeLineJoin="round" />
        <path
            android:fillColor="${COLORS.glyph}"
            android:pathData="${nodesPathData()}" />
    </group>
</vector>
`;
const background = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/generate.mjs from tools/icon/icon.mjs. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0 L108,0 L108,108 L0,108 Z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="18"
                android:startY="18"
                android:endX="90"
                android:endY="90">
                <item android:offset="0" android:color="${COLORS.bgStart}" />
                <item android:offset="1" android:color="${COLORS.bgEnd}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
`;
fs.writeFileSync(path.join(RES, 'drawable/ic_launcher_foreground.xml'), foreground);
fs.writeFileSync(path.join(RES, 'drawable/ic_launcher_background.xml'), background);
console.log('wrote android/app/src/main/res/drawable/ic_launcher_{foreground,background}.xml');

// Legacy launcher PNGs (Android 7 and older launchers without adaptive icons).
for (const [dir, size] of Object.entries({ mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 })) {
  await png(path.join(RES, `mipmap-${dir}/ic_launcher.png`), size, 'rounded');
  await png(path.join(RES, `mipmap-${dir}/ic_launcher_round.png`), size, 'circle');
}

// iOS: full-bleed opaque squares; iOS applies its own mask.
const contents = JSON.parse(fs.readFileSync(path.join(IOS, 'Contents.json'), 'utf8'));
for (const image of contents.images) {
  if (!image.filename) continue;
  const size = Math.round(parseFloat(image.size) * parseFloat(image.scale));
  await png(path.join(IOS, image.filename), size, 'square', true);
}

await png(path.join(ROOT, 'showcase/img/icon.png'), 512, 'rounded');

console.log('\nIn-app logo (src/ui/track.tsx, AppLogo), 100-unit box:');
console.log(`  transform="translate(${r4(T.tx)} ${r4(T.ty)}) scale(${r4(T.s)})"`);
await browser.close();
